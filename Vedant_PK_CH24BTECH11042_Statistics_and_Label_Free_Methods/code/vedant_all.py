"""
One command for ALL of Vedant's statistics work. Run from ~/granule_project:

    python vedant_all.py

It needs vedant_stats.py in the same folder, plus the files from the training and video-3 runs:
    rahul_5fold_outputs/runs.csv, runs_extra.csv
    rahul_v3_outputs/v3_tiles.csv, pseudo_vs_hand.csv, overlays/

It will
  1. run the 5-fold tests + violins   -> slides_assets/stats_folds/
  2. run the video-3 tests + violins  -> slides_assets/stats_video3/
  3. tabulate model size / speed, pseudo-label-vs-hand-label scores
  4. write slides_assets/summary.md   (tables + auto-written takeaways, only what the numbers support)
  5. zip everything                   -> slides_assets.zip
"""
import argparse, os, shutil, subprocess, sys
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
MODELS = ["UNet", "DWUNet", "DWAttUNet"]
METRICS = ["dice", "iou", "f1", "aji", "ap50"]


def md_table(df, floatfmt="{:.3f}"):
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append(floatfmt.format(v) if isinstance(v, (float, np.floating)) else str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def run_stats(csv, mode, out):
    cmd = [sys.executable, os.path.join(HERE, "vedant_stats.py"), "--file", csv, "--mode", mode, "--out", out]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout, r.stderr)
        raise SystemExit(f"vedant_stats.py failed on {csv}")
    return r.stdout


def mean_std_table(df):
    rows = []
    for m in MODELS:
        d = df[df.model == m]
        if d.empty:
            continue
        row = {"model": m}
        for k in METRICS:
            row[k] = f"{d[k].mean():.3f} ± {d[k].std(ddof=1):.3f}"
        rows.append(row)
    return pd.DataFrame(rows)


def significance_text(stats_dir, label):
    pw = pd.read_csv(os.path.join(stats_dir, "pairwise_tests.csv"))
    fr = pd.read_csv(os.path.join(stats_dir, "friedman.csv"))
    sig = pw[pw["p_holm"] < 0.05]
    n_units = int(pw["n_units"].iloc[0])
    lines = []
    if sig.empty:
        lines.append(f"- {label}: after Holm correction **no pairwise difference is significant (p < 0.05)** "
                     f"in any of the 5 metrics ({n_units} paired units per model).")
    else:
        lines.append(f"- {label}: pairs significant after Holm correction (p < 0.05), {n_units} paired units:")
        for _, r in sig.iterrows():
            better = r.model_a if r.mean_diff_a_minus_b > 0 else r.model_b
            worse = r.model_b if r.mean_diff_a_minus_b > 0 else r.model_a
            lines.append(f"  - {r.metric}: {better} > {worse} (diff {abs(r.mean_diff_a_minus_b):.3f}, "
                         f"p_holm {r.p_holm:.4f}, dz {r.cohens_dz:.2f})")
    fsig = fr[fr["p"] < 0.05]
    if fsig.empty:
        lines.append("- Friedman test (do the 3 models differ at all?): not significant for any metric.")
    else:
        lines.append("- Friedman test is significant for: " + ", ".join(f"{r.metric} (p={r.p:.3f})" for _, r in fsig.iterrows()) + ".")
    return "\n".join(lines), pw, fr


def leaders(df):
    out = []
    for k in METRICS:
        means = df.groupby("model")[k].mean()
        out.append(f"{k}: {means.idxmax()} ({means.max():.3f})")
    return "; ".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--folds-csv", default="rahul_5fold_outputs/runs.csv")
    ap.add_argument("--extra-csv", default="rahul_5fold_outputs/runs_extra.csv")
    ap.add_argument("--v3-csv", default="rahul_v3_outputs/v3_tiles.csv")
    ap.add_argument("--pseudo-csv", default="rahul_v3_outputs/pseudo_vs_hand.csv")
    ap.add_argument("--methods-csv", default="rahul_v3_outputs/extra_methods_vs_hand.csv",
                    help="label-free methods scored by score_video3.py --extra (optional)")
    ap.add_argument("--overlays", default="rahul_v3_outputs/overlays")
    ap.add_argument("--out", default="slides_assets")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    md = ["# Results summary (auto-generated by vedant_all.py)\n"]

    # ---- 1. 5-fold
    runs = pd.read_csv(a.folds_csv)
    run_stats(a.folds_csv, "folds", os.path.join(a.out, "stats_folds"))
    sig_text, pw5, fr5 = significance_text(os.path.join(a.out, "stats_folds"), "5-fold CV")
    md += ["## 1. 5-fold cross-validation (test tiles with pseudo-label ground truth)\n",
           f"{runs.groupby('model')['fold'].nunique().min()} folds x {runs.groupby('model')['seed'].nunique().min()} seeds "
           f"= {len(runs) // max(runs.model.nunique(), 1)} runs per model. Mean ± std over all runs:\n",
           md_table(mean_std_table(runs)), "",
           "Best mean per metric: " + leaders(runs) + "\n", sig_text + "\n",
           "Pairwise paired t-tests on per-fold means (seeds averaged), Holm-corrected:\n",
           md_table(pw5[["metric", "model_a", "model_b", "mean_diff_a_minus_b", "p_raw", "p_holm", "cohens_dz"]]), ""]

    # ---- 2. video-3
    v3 = None
    if os.path.exists(a.v3_csv):
        v3 = pd.read_csv(a.v3_csv)
        run_stats(a.v3_csv, "tiles", os.path.join(a.out, "stats_video3"))
        sig3, pw3, fr3 = significance_text(os.path.join(a.out, "stats_video3"), "Video-3")
        n_tiles = v3["tile"].nunique()
        tot = v3.groupby(["model", "fold", "seed"])[["tp", "fp", "fn"]].sum().groupby("model").mean().round(1).reset_index()
        tot["precision"] = tot.tp / (tot.tp + tot.fp).clip(lower=1)
        tot["recall"] = tot.tp / (tot.tp + tot.fn).clip(lower=1)
        md += [f"## 2. Video-3 (HAND-labelled ground truth, {n_tiles} tiles)\n",
               "Mean ± std over all (checkpoint, tile) scores:\n", md_table(mean_std_table(v3)), "",
               "Best mean per metric: " + leaders(v3) + "\n",
               "Granule counts summed over the tiles (mean over 15 checkpoints) and precision / recall:\n",
               md_table(tot), "", sig3 + "\n",
               f"Only {n_tiles} tiles: p-values here have little power, treat as indicative.\n",
               "Pairwise paired t-tests per tile (checkpoints averaged), Holm-corrected:\n",
               md_table(pw3[["metric", "model_a", "model_b", "mean_diff_a_minus_b", "p_raw", "p_holm", "cohens_dz"]]), ""]
        if os.path.isdir(a.overlays):
            shutil.copytree(a.overlays, os.path.join(a.out, "overlays"), dirs_exist_ok=True)
    else:
        md.append(f"## 2. Video-3\n\n{a.v3_csv} not found - skipped.\n")

    # ---- 3. size / speed
    if os.path.exists(a.extra_csv):
        e = pd.read_csv(a.extra_csv)
        cols = [c for c in ["params", "epochs", "train_minutes", "tiles_per_s", "precision", "recall", "loc_err"] if c in e.columns]
        t = e.groupby("model")[cols].mean().reindex(MODELS).reset_index()
        if "params" in t:
            t["params"] = t["params"].round(0).astype(int)
            t["size_vs_UNet"] = (t["params"] / t.loc[t.model == "UNet", "params"].iloc[0]).round(2)
        md += ["## 3. Model size and speed (5-fold runs, MacBook Air M3 GPU)\n", md_table(t), ""]

    # ---- 4. pseudo vs hand, and every approach side by side on the hand-labelled tiles
    others = []
    if os.path.exists(a.pseudo_csv):
        p = pd.read_csv(a.pseudo_csv)
        s_ = {k: p[k].mean() for k in METRICS}
        tp, fp, fn = int(p.tp.sum()), int(p.fp.sum()), int(p.fn.sum())
        md += ["## 4. How good are the pseudo-labels? (classical labeller scored against the hand labels)\n",
               "Mean over tiles: " + ", ".join(f"{k} {v:.3f}" for k, v in s_.items()) + f". Granule counts: TP {tp}, FP {fp}, FN {fn} "
               f"(precision {tp / max(tp + fp, 1):.2f}, recall {tp / max(tp + fn, 1):.2f}).\n"]
        others.append(p)
    if os.path.exists(a.methods_csv):
        others.append(pd.read_csv(a.methods_csv))
    if v3 is not None and others:
        net = v3.groupby(["model", "fold", "seed"])[METRICS + ["tp", "fp", "fn"]].agg(
            {**{k: "mean" for k in METRICS}, **{k: "sum" for k in ["tp", "fp", "fn"]}}).groupby("model").mean()
        oth = pd.concat(others).groupby("model")[METRICS + ["tp", "fp", "fn"]].agg(
            {**{k: "mean" for k in METRICS}, **{k: "sum" for k in ["tp", "fp", "fn"]}})
        allm = pd.concat([net, oth])
        allm["precision"] = allm.tp / (allm.tp + allm.fp).clip(lower=1)
        allm["recall"] = allm.tp / (allm.tp + allm.fn).clip(lower=1)
        allm = allm.round(3).reset_index().rename(columns={"index": "model"})
        md += ["## 4b. Every approach on the hand-labelled tiles (human labels = ground truth)\n",
               "Trained networks: mean over their 15 checkpoints. Pseudo-labeller and label-free methods: a single deterministic run each "
               "(no seeds/folds), so no p-values for them. Scores are means over the tiles, counts are summed over the tiles.\n",
               md_table(allm), ""]
        allm.to_csv(os.path.join(a.out, "all_methods_video3.csv"), index=False)

    md += ["## 5. Caveats to state on the slides\n",
           "- 5-fold ground truth is the classical pseudo-labeller, not human annotation: scores measure agreement with it.",
           "- Only 5 folds: the smallest possible Wilcoxon p-value is 0.0625, so tests use paired t-tests on per-fold means with Holm correction.",
           "- The 3 seeds in a fold are not independent samples, so seeds are averaged before testing; violins still show all runs.",
           "- Video-3 hand labels cover a small number of tiles and one annotator.",
           "- Instances come from connected components of a binary mask, so touching granules are merged into one.\n"]

    path = os.path.join(a.out, "summary.md")
    open(path, "w").write("\n".join(md))
    shutil.make_archive(a.out, "zip", ".", a.out)
    print(f"Wrote {path}\nZipped to {a.out}.zip\n")
    print("\n".join(md[:14]))


if __name__ == "__main__":
    main()
